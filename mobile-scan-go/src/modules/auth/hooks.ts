import { useMutation, useQuery } from '@tanstack/react-query';
import { authApi } from './api';
import { tokens } from '../../core/session/tokens';
export const useCustomer = () => useQuery({queryKey:['auth','me'],queryFn:authApi.me});
export const useLogin = () => useMutation({mutationFn:({phone,password}:{phone:string;password:string})=>authApi.login(phone,password), onSuccess:r=>tokens.save(r.token,r.refreshToken)});
export const useGoogleAuth = () => useMutation({mutationFn:authApi.google, onSuccess:r=>tokens.save(r.token,r.refreshToken)});
export const useRegister = () => useMutation({mutationFn:authApi.register, onSuccess:r=>tokens.save(r.token,r.refreshToken)});
export const useSendOtp=()=>useMutation({mutationFn:({phone,purpose}:{phone:string;purpose:'REGISTRATION'|'FORGOT_PASSWORD'|'LOGIN_VERIFY'})=>authApi.sendOtp(phone,purpose)});
export const useLogout=()=>useMutation({mutationFn:authApi.logout});
export const useLogoutAll=()=>useMutation({mutationFn:authApi.logoutAll});
